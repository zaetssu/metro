def build_metro_graph() -> Graph:
    """Собрать граф метро из станций и перегонов."""
    metro = Graph()
    for station in STATIONS:
        metro.add_vertex(station)
    for u, v, weight in EDGES:
        metro.add_edge(u, v, weight)
    return metro
